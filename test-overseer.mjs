import assert from 'node:assert/strict';
import {OVERSEER_MAX_HP,createOverseer,OVERSEER_NODES} from './overseer-rules.js';
import {roofObstacles} from './roof-data.js';
const b=createOverseer(),p={x:0,z:-10,feetY:0};
b.reset(true);assert.equal(b.damage('core',100),0);assert.equal(b.blocking,true);
assert.equal(b.damage(0,65),65);assert.equal(b.state.phase,'shield');b.damage(1,65);assert.equal(b.state.phase,'exposed');assert.equal(b.damage('core',100),100);
const before=b.state.timer;b.tick(0,p);assert.equal(b.state.timer,before);b.tick(8,p);assert.deepEqual(b.state.nodes,[65,65]);assert.equal(b.state.phase,'shield');
b.reset(true);assert.equal(b.tick(2,p),0);assert.equal(b.state.attack,'warning');const aim=b.state.aim;b.tick(.5,{x:10,z:-10});assert.equal(b.state.aim,aim);assert.equal(b.tick(1,p),18);assert.equal(b.tick(.1,p),0);
b.reset(true);b.tick(2,p);assert.equal(b.tick(1.5,{...p,feetY:1}),0);assert.equal(b.tick(.1,p),18);
b.reset(true);b.tick(2,p);assert.equal(b.tick(1.5,{...p,x:5}),0);
b.reset(true);b.tick(2,p);assert.equal(b.tick(1.5,{...p,blocked:true}),0);
b.reset(true);b.tick(2,p);b.damage(0,65);b.damage(1,65);assert.equal(b.state.attack,'rest');assert.equal(b.tick(.1,p),0);assert.equal(b.damage('core',OVERSEER_MAX_HP+100),OVERSEER_MAX_HP);assert.equal(b.blocking,false);assert.equal(b.tick(10,p),0);
b.reset(true);assert.equal(b.state.hp,OVERSEER_MAX_HP);b.reset(false);assert.equal(b.tick(3,p),0);assert.equal(b.damage(0,100),0);
for(const n of OVERSEER_NODES)assert.ok(!roofObstacles(3).some(o=>Math.abs(n.x-o.x)<o.w/2+1&&Math.abs(n.z-o.z)<o.d/2+1),'node must have accessible approach');
console.log('PASS: Overseer shield/nodes/exposure/reset, locked telegraph, lateral/jump/cover avoidance, single-hit arc, pause, defeat and node clearance');

assert.equal(OVERSEER_MAX_HP,1920);
b.reset(true);b.damage(0,65);b.damage(1,65);
b.damage('core',959);assert.equal(b.state.hp,961);assert.equal(b.state.tier,1);
b.damage('core',1);assert.equal(b.state.hp,960);assert.equal(b.state.tier,2);
b.reset(true);assert.equal(b.state.hp,1920);assert.equal(b.state.tier,1);assert.deepEqual(b.state.nodes,[65,65]);
console.log('PASS: 1920 HP, exact 960 HP phase-two threshold, retry and unchanged nodes');
