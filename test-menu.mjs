import assert from 'node:assert/strict';
import {HOME_MENU_ITEMS, MENU_CHAPTERS, chapterInfo, nextChapter, chapterURL, formatPlayTime, readSingleSlots, continueTarget, primaryAction} from './menu-state.js';
import {CHAPTERS} from './journey.js';

assert.deepEqual(HOME_MENU_ITEMS.map(item => item.label), ['新游戏', '继续游戏', '选择关卡', '成就', '设置']);
assert.equal(new Set(HOME_MENU_ITEMS.map(item => item.id)).size, 5);
assert(HOME_MENU_ITEMS.some(item => item.id === 'menu-achievements' && item.icon === 'star'));
assert(Object.isFrozen(HOME_MENU_ITEMS) && HOME_MENU_ITEMS.every(Object.isFrozen));

const base = {state: 'ready', mode: 'campaign', map: 'reactor', checkpoint: null, journey: null};
const checkpoint = {stageIndex: 1, health: 80, selected: 0, x: 0, z: 29, yaw: 0, pitch: 0, time: 42, kills: 3, rounds: [20, 6, 10], reserves: [100, 30, 60], collected: []};
const active = {version: 4, chapter: 2, status: 'active', checkpoint: {...checkpoint}, results: [{time: 60, kills: 10}, {time: 70, kills: 11}]};
const between = {...active, status: 'between', checkpoint: null, results: [...active.results, {time: 80, kills: 12}]};
const complete = {...between, chapter: 6, status: 'complete', results: Array.from({length: 7}, () => ({time: 60, kills: 10}))};
assert.deepEqual(MENU_CHAPTERS.map(c => [c.map, c.name]), CHAPTERS.map(c => [c.map, c.name]));
assert.equal(chapterInfo('roof').number, '03');
assert.equal(nextChapter('reactor').map, 'station');
assert.equal(nextChapter('harbor').map, 'orbital');
assert.equal(nextChapter('orbital'), null, 'never offer a nonexistent eighth chapter');
assert.equal(chapterURL('roof', 'journey'), '?map=roof&mode=journey&menu=chapter');
assert.equal(chapterURL('roof', 'campaign', 'continue'), '?map=roof&menu=continue');
assert.throws(() => chapterURL('https://invalid.example'));
assert.equal(formatPlayTime(125.8), '02:05');
assert.equal(formatPlayTime(Infinity), '00:00');
assert.equal(formatPlayTime(-2), '00:00');
assert.equal(continueTarget(base), null, 'no misleading continue button for an empty save');
assert.equal(continueTarget({...base, journey: complete}), null, 'completed campaign is not a resumable active game');
assert.equal(continueTarget({...base, journey: active}).map, 'roof');
assert.equal(continueTarget({...base, journey: between}).map, 'tower');
assert.equal(continueTarget({...base, state: 'paused', journey: active}).kind, 'session', 'pause resumes memory, not a reset');
assert.equal(continueTarget({...base, state: 'paused', pending: true, journey: active}).kind, 'pending');
assert.equal(continueTarget({...base, slots: [{map: 'train', stage: 2}]}).map, 'train');
assert.equal(continueTarget({...base, slots: [{map: 'train', stage: 2}, {map: 'harbor', stage: 1}]}).kind, 'slots');
assert.equal(continueTarget({...base, checkpoint}).kind, 'single');
assert.equal(primaryAction(base).kind, 'start-single');
assert.equal(primaryAction({...base, checkpoint}).kind, 'continue-single');
assert.equal(primaryAction({...base, state: 'paused', journey: active}).kind, 'resume');
assert.equal(primaryAction({...base, state: 'lost', checkpoint}).kind, 'retry');
assert.equal(primaryAction({...base, state: 'lost'}).kind, 'restart');
assert.equal(primaryAction({...base, state: 'won', mode: 'replay'}).kind, 'retry');
assert.equal(primaryAction({...base, mode: 'journey', journey: active}).kind, 'continue-journey');
assert.equal(primaryAction({...base, mode: 'journey', journey: between}).map, 'tower');
assert.equal(primaryAction({...base, mode: 'journey', journey: between, state: 'won'}).kind, 'advance');
assert.equal(primaryAction({...base, mode: 'journey', journey: active, pending: true, state: 'won'}).kind, 'save-result');
assert.equal(primaryAction({...base, mode: 'journey', journey: complete, state: 'won'}).kind, 'home');
assert.equal(primaryAction({...base, state: 'won'}).kind, 'next-single');
assert.equal(primaryAction({...base, map: 'harbor', state: 'won'}).kind, 'next-single');
assert.equal(primaryAction({...base, map: 'orbital', state: 'won'}).kind, 'home');
assert.equal(primaryAction({...base, state: 'won', mode: 'journey', journey: between, checkpoint}, true).kind, 'continue-single', 'explicit standalone selection stays standalone');
const data = new Map(); let writes = 0;
const storage = {getItem: key => data.get(key) ?? null, setItem() { writes++; }, removeItem() { writes++; }};
assert.deepEqual(readSingleSlots(storage), {slots: [], error: false});
data.set('neon-eclipse.campaign.v1', JSON.stringify({version: 1, unlocked: 1, checkpoint, completed: false}));
data.set('neon-eclipse.train.v1', JSON.stringify({version: 1, unlocked: 2, checkpoint: {...checkpoint, stageIndex: 2, collected: [CHAPTERS[4].supplies[0].id]}, completed: false}));
const old = JSON.stringify([...data]);
assert.deepEqual(readSingleSlots(storage), {slots: [{map: 'reactor', stage: 1}, {map: 'train', stage: 2}], error: false});
assert.equal(JSON.stringify([...data]), old); assert.equal(writes, 0);
data.set('neon-eclipse.harbor.v1', '{corrupt');
assert.equal(readSingleSlots(storage).error, true);
assert.equal(data.get('neon-eclipse.harbor.v1'), '{corrupt');
data.set('neon-eclipse.harbor.v1', JSON.stringify({version: 1, unlocked: 0, checkpoint: {...checkpoint, collected: [CHAPTERS[0].supplies[0].id]}}));
assert.equal(readSingleSlots(storage).error, true, 'map-specific supply validation is retained');
assert.equal(readSingleSlots(null).error, true);
assert.equal(readSingleSlots({getItem() { throw new Error('denied'); }}).error, true);
assert.equal(writes, 0, 'menu discovery never mutates saves');
console.log('PASS: five-entry menu including achievements, empty/active/between/complete saves, pause vs checkpoint, one clear next-chapter action, pending-save protection, training/single isolation, final chapter, safe links and read-only map-specific save discovery');
