import assert from 'node:assert/strict';
import {SENTRY,sentryScanYaw,inSentrySector,chooseSentrySite} from './sentry-rules.js';
import {ENEMY_TYPES,resolveEnemyDamage} from './enemy-rules.js';
import {STAGES} from './mission.js';
const origin={x:0,y:1.42,z:0};
assert(inSentrySector(origin,0,{x:0,y:1.35,z:10}));
for(const target of [{x:10,y:1.35,z:0},{x:0,y:1.35,z:-10},{x:0,y:1.35,z:23},{x:0,y:30,z:10},{x:0,y:1.35,z:1},{x:NaN,y:1,z:10}])assert(!inSentrySector(origin,0,target));
assert(inSentrySector(origin,Math.PI*2,{x:0,y:1.42,z:22}));
for(let i=0;i<1000;i++)assert(Math.abs(sentryScanYaw(2,i*.1)-2)<=SENTRY.sweep+1e-9);
const site=chooseSentrySite({x:28,z:0},{x:-28,z:0},[]);assert(site);assert.equal(Math.hypot(site.x-28,site.z),8);assert.equal(chooseSentrySite({x:28,z:0},{x:-28,z:0},[{x:0,z:0,w:100,d:100,h:10}]),null);
assert.notDeepEqual(chooseSentrySite({x:28,z:0},{x:-28,z:0},[],[{hp:1,radius:.75,group:{position:site}}]),site);
assert.notDeepEqual(chooseSentrySite({x:28,z:0},{x:-28,z:0},[],[],[site]),site);
const e={type:'sentry',group:{position:origin,rotation:{y:0}}};
assert.equal(resolveEnemyDamage(e,100,'body',{x:0,z:10}).damage,35);assert.equal(resolveEnemyDamage(e,100,'body',{x:10,z:0}).damage,100);assert.equal(resolveEnemyDamage(e,100,'core',{x:0,z:-10}).damage,200);
assert.equal(ENEMY_TYPES.sentry.hp,150);assert.equal(ENEMY_TYPES.sentry.speed,0);assert.deepEqual(STAGES.filter(s=>s.sentry).map(s=>s.id),['access']);assert.equal(STAGES[1].count,6);
console.log('PASS: bounded scan, range/height/point-blank/rear exclusion, safe occupied spawn, frontal armor/rear core, access-only six guards retained');
